'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const cli = path.resolve(__dirname, '../../scripts/layout.js');
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'harness-layout-'));
const root = path.join(home, '.claude');
fs.mkdirSync(root);
const put = (name, data) => { const p = path.join(root, name); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, data); };
const run = (...args) => spawnSync(process.execPath, [cli, '--root', root, ...args], { encoding: 'utf8', cwd: root });
try {
  put('sessions/2026-09-29-example-session.tmp', 'memo');
  put('sessions/native.json', '{"pid":123}');
  put('.state/guardrail-candidates.jsonl', '{"source":"old"}\n');
  put('runs/old/meta.json', '{"run_id":"old"}');
  put('feedback/drafts/draft.json', 'native feedback');
  put('session-aliases.json', JSON.stringify({ aliases: { saved: { sessionPath: path.join(root, 'sessions/2026-09-29-example-session.tmp') } } }));
  let result = run('--apply');
  assert.strictEqual(result.status, 0, result.stderr);
  assert.strictEqual(fs.readFileSync(path.join(root, 'harness/data/sessions/2026-09-29-example-session.tmp'), 'utf8'), 'memo');
  assert.strictEqual(fs.readFileSync(path.join(root, 'sessions/native.json'), 'utf8'), '{"pid":123}');
  assert.strictEqual(fs.readFileSync(path.join(root, 'feedback/drafts/draft.json'), 'utf8'), 'native feedback');
  assert.ok(!fs.existsSync(path.join(root, '.state/guardrail-candidates.jsonl')));
  assert.ok(fs.existsSync(path.join(root, 'harness/data/runs/old/meta.json')));
  result = run('--apply');
  assert.strictEqual(result.status, 0, result.stderr);
  assert.deepStrictEqual(JSON.parse(result.stdout).moves, []);
  const resolved = spawnSync(process.execPath, ['-e', `process.stdout.write(require(${JSON.stringify(path.resolve(__dirname, '../../scripts/lib/session-aliases'))}).resolveSessionAlias('saved'))`], { env: { ...process.env, HOME: home, USERPROFILE: home }, encoding: 'utf8' });
  assert.strictEqual(resolved.status, 0, resolved.stderr);
  assert.strictEqual(resolved.stdout, path.join(root, 'harness/data/sessions/2026-09-29-example-session.tmp'));
  const git = (...args) => { const r = spawnSync('git', args, { cwd: root, encoding: 'utf8' }); assert.strictEqual(r.status, 0, r.stderr); };
  git('init', '-q', '-b', 'main');
  git('-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '--allow-empty', '-qm', 'initial');
  const worktree = path.join(home, 'development', 'issue-26');
  git('worktree', 'add', '-q', '-b', 'issue-26', worktree);
  fs.writeFileSync(path.join(worktree, 'verification-summary.md'), '# Verification Summary\n\n## Scope\nfixture\n\n## Commands Run\nnode test\n\n## RED Evidence\nfailed\n\n## Verification Outcome\npassed\n');
  const runtimeEnv = { ...process.env, HOME: home, USERPROFILE: home };
  delete runtimeEnv.CLAUDE_DISABLE_RUN_RECORD;
  const native = spawnSync(process.execPath, [path.resolve(__dirname, '../../scripts/hooks/runtime-session.js'), '--runtime', 'codex'], {
    cwd: worktree, env: runtimeEnv, encoding: 'utf8',
    input: JSON.stringify({ session_id: 'isolated', cwd: worktree, hook_event_name: 'SessionStart' }),
  });
  assert.strictEqual(native.status, 0, native.stderr);
  assert.ok(fs.existsSync(path.join(worktree, 'harness/data/runs')), `outside worktree must keep its own evidence: ${native.stderr}`);
  put('runs/new/meta.json', 'keep source');
  put('metrics/costs.jsonl', 'source history');
  put('harness/data/metrics/costs.jsonl', 'destination history');
  const conflict = run('--apply');
  assert.strictEqual(conflict.status, 1);
  assert.match(conflict.stderr, /destination already exists/);
  assert.strictEqual(fs.readFileSync(path.join(root, 'runs/new/meta.json'), 'utf8'), 'keep source');
  assert.strictEqual(fs.readFileSync(path.join(root, 'metrics/costs.jsonl'), 'utf8'), 'source history');
  assert.strictEqual(fs.readFileSync(path.join(root, 'harness/data/metrics/costs.jsonl'), 'utf8'), 'destination history');
  fs.rmSync(path.join(root, 'metrics'), { recursive: true });
  const outside = path.join(home, 'outside');
  fs.mkdirSync(outside); fs.writeFileSync(path.join(outside, 'keep'), 'outside');
  fs.symlinkSync(outside, path.join(root, 'metrics'), 'dir');
  assert.match(run('--apply').stderr, /refusing symlink/);
  assert.strictEqual(fs.readFileSync(path.join(outside, 'keep'), 'utf8'), 'outside');
  fs.unlinkSync(path.join(root, 'metrics'));
  fs.rmSync(path.join(root, 'harness/data/metrics'), { recursive: true });
  fs.symlinkSync(outside, path.join(root, 'harness/data/metrics'), 'dir');
  put('metrics/costs.jsonl', 'source');
  assert.match(run('--apply').stderr, /refusing symlink/);
  assert.ok(!fs.existsSync(path.join(outside, 'costs.jsonl')));
  console.log('Results: Passed: 4, Failed: 0');
} finally { fs.rmSync(home, { recursive: true, force: true }); }
